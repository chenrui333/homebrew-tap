"""Generate the cask status report from an installed Homebrew tap."""

import argparse
import json
import os
import re
import subprocess
from pathlib import Path
from urllib.parse import quote, urlsplit


TAP = "chenrui333/tap"
TOKEN = re.compile(r"[a-z0-9][a-z0-9+_.@-]*")
MARKDOWN = re.compile(r"[\\`*_{}\[\]()<>|&~!]")


def brew_json(*args):
    result = subprocess.run(
        ["brew", *args], check=True, capture_output=True, text=True,
        env={**os.environ, "HOMEBREW_NO_AUTO_UPDATE": "1"},
    )
    return json.loads(result.stdout)


def tap_tokens(data):
    if not isinstance(data, list) or len(data) != 1 or not isinstance(data[0], dict):
        raise ValueError(f"Expected metadata for exactly one tap: {TAP}")
    tap = data[0]
    if tap.get("name") != TAP or tap.get("installed") is not True:
        raise ValueError(f"Homebrew tap is missing: {TAP}")
    names = tap.get("cask_tokens")
    files = tap.get("cask_files")
    prefix = f"{TAP}/"
    if not isinstance(names, list) or not names or any(
        not isinstance(name, str) or not name.startswith(prefix)
        or not TOKEN.fullmatch(name[len(prefix):]) for name in names
    ):
        raise ValueError(f"Missing or invalid cask tokens for {TAP}")
    if len(set(names)) != len(names):
        raise ValueError(f"Duplicate cask tokens for {TAP}")
    if (not isinstance(files, list) or len(files) != len(names)
            or any(not isinstance(file, str) or not file.endswith(".rb") for file in files)
            or {prefix + Path(file).stem for file in files} != set(names)):
        raise ValueError(f"Cask tokens do not match the cask files for {TAP}")
    return sorted(names)


def cask_records(data, names):
    expected = set(names)
    records = {}
    casks = data.get("casks") if isinstance(data, dict) else None
    if not isinstance(casks, list):
        raise ValueError("Missing Homebrew cask metadata")
    for cask in casks:
        if not isinstance(cask, dict):
            raise ValueError("Invalid Homebrew cask record")
        name = cask.get("full_token")
        if (not isinstance(name, str) or name not in expected or cask.get("tap") != TAP
                or cask.get("token") != name.rsplit("/", 1)[1]):
            raise ValueError(f"Unexpected cask lookup result: {name!r}")
        if name in records:
            raise ValueError(f"Duplicate cask lookup result: {name}")
        records[name] = cask
    if missing := expected - records.keys():
        raise ValueError(f"Missing cask lookup results: {', '.join(sorted(missing))}")
    return [records[name] for name in names]


def text(value):
    return " ".join(value.split()) if isinstance(value, str) else ""


def cell(value):
    return MARKDOWN.sub(lambda match: f"&#{ord(match[0])};", text(value)) or "—"


def homepage(value):
    label = cell(value)
    if not isinstance(value, str) or not value or any(not char.isprintable() for char in value):
        return label
    try:
        url = urlsplit(value)
        if url.scheme not in {"http", "https"} or not url.hostname or url.username is not None:
            return label
    except ValueError:
        return label
    destination = quote(value, safe=":/?#[]@!$&'()*+,;=%-._~").replace("&", "&amp;")
    return f"[{label}](<{destination}>)"


def lifecycle(cask):
    if cask.get("disabled") is True:
        state, key = "Disabled", "disable"
    elif cask.get("deprecated") is True:
        state, key = "Deprecated", "deprecation"
    elif cask.get("disabled") is False and cask.get("deprecated") is False:
        return "Active"
    else:
        return "Unknown"
    details = [cell(value) for suffix in ("date", "reason") if text(value := cask.get(f"{key}_{suffix}"))]
    return ": ".join([state, ", ".join(details)]) if details else state


def render(casks):
    lines = [
        "# Cask Status",
        "",
        "<!-- Generated by cask-status/generate_cask_status.py. Do not edit. -->",
        "",
        "Versions and lifecycle status reflect Homebrew metadata on the report runner.",
        "",
        "| Cask | Version | Homepage | Lifecycle |",
        "| --- | --- | --- | --- |",
    ]
    for cask in sorted(casks, key=lambda record: record["token"]):
        fields = (f"`{cask['token']}`", cell(cask.get("version")), homepage(cask.get("homepage")), lifecycle(cask))
        lines.append(f"| {' | '.join(fields)} |")
    return "\n".join(lines) + "\n"


def generate():
    names = tap_tokens(brew_json("tap-info", TAP, "--json"))
    return render(cask_records(brew_json("info", "--json=v2", "--cask", *names), names))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()
    try:
        report = generate()
        args.output.write_text(report, encoding="utf-8")
    except subprocess.CalledProcessError as error:
        parser.exit(1, f"{error}\n{error.stderr}")
    except (OSError, ValueError) as error:
        parser.exit(1, f"{error}\n")


if __name__ == "__main__":
    main()
