  def fetch
    # maturin/PyO3 run offline `cargo metadata`, which needs crates for all targets.
    resource("libcst").stage { cd("native") { system "cargo", "fetch", "--locked" } }
  end

  def install
    build_resources = %w[
      flit-core
      packaging
      pathspec
      poetry-core
      setuptools
      calver
      cython
      semantic-version
      tomlkit
      trove-classifiers
      vcs-versioning
      setuptools-scm
      pluggy
      hatchling
      hatch-fancy-pypi-readme
      hatch-vcs
      setuptools-rust
      wheel
    ]

    # Cython is only a build tool for pyyaml-ft; skip compiling Cython itself.
    ENV["NO_CYTHON_COMPILE"] = "true"
    ENV["CARGO_NET_OFFLINE"] = "true"

    venv = virtualenv_create(libexec, "python3.13")
    build_resources.each do |name|
      venv.pip_install resource(name), build_isolation: false
    end
    venv.pip_install resources.reject { |r| build_resources.include?(r.name) }, build_isolation: false
    venv.pip_install_and_link buildpath, build_isolation: false

    generate_completions_from_executable(bin/"usort", shells: [:fish, :zsh], shell_parameter_format: :click)
  end

