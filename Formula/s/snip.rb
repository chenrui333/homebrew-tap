  def install
    build_resources = %w[
      flit-core
      packaging
      pathspec
      poetry-core
      setuptools
      calver
      tomlkit
      trove-classifiers
      vcs-versioning
      setuptools-scm
      pluggy
      hatchling
      hatch-vcs
    ]

    venv = virtualenv_create(libexec, "python3.14")
    build_resources.each do |name|
      venv.pip_install resource(name), build_isolation: false
    end
    venv.pip_install resources.reject { |r| build_resources.include?(r.name) }, build_isolation: false
    venv.pip_install_and_link buildpath, build_isolation: false

    generate_completions_from_executable(bin/"snip", "init", shells: [:bash, :zsh])
  end

  test do
    snippet_dir = testpath/"snippets"
    source_file = testpath/"hello.py"
    source_file.write "print(\"hello\")\n"

    system bin/"snip", "--db", snippet_dir, "--add", source_file

    assert_match version.to_s, shell_output("#{bin}/snip --version")
    assert_equal "hello", shell_output("#{bin}/snip --db #{snippet_dir} --list").strip

    snippet_json = shell_output("#{bin}/snip --db #{snippet_dir} --json hello")
    assert_match "\"title\": \"hello\"", snippet_json
    assert_match "\"language\": \"python\"", snippet_json

    export_json = shell_output("#{bin}/snip --db #{snippet_dir} --export")
    assert_match "\"content\": \"print(\\\"hello\\\")\\n\"", export_json
  end
