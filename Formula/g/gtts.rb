    test_script = testpath/"test_gtts_cli.py"
    test_script.write <<~'PY'
      import runpy
      import sys
      from unittest.mock import patch

      class Response:
          status_code = 200

          def __init__(self, request):
              self.request = request

          def raise_for_status(self):
              pass

          def iter_lines(self, chunk_size):
              yield b'jQ1olc","[\\"aGVsbG8=\\"]'

      def fake_send(session, request, **kwargs):
          return Response(request)

      sys.argv = [sys.argv[1], "Hello, world!", "-o", sys.argv[2]]
      with patch("requests.Session.send", fake_send):
          try:
              runpy.run_path(sys.argv[0], run_name="__main__")
          except SystemExit as error:
              assert error.code == 0
    PY

    system libexec/"bin/python", test_script, bin/"gtts-cli", output
    assert_equal "hello", output.read
  end
