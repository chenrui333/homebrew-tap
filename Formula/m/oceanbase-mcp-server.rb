    venv = virtualenv_create(libexec, "python3.13")
    build_resources.each do |name|
      venv.pip_install resource(name), build_isolation: false
    end
    venv.pip_install resources.reject { |r| build_resources.include?(r.name) }, build_isolation: false
    venv.pip_install_and_link buildpath, build_isolation: false
  end

  test do
    require "json"
    require "open3"
    require "timeout"

    output = shell_output("#{bin}/oceanbase_mcp_server 2>&1", 1)
    assert_match "Missing required database configuration", output

    ENV["OB_USER"] = "homebrew"
    ENV["OB_PASSWORD"] = "homebrew"
    ENV["OB_DATABASE"] = "homebrew"

    Open3.popen2(bin/"oceanbase_mcp_server") do |input, output, process|
      Timeout.timeout(30) do
        read_response = lambda do
          loop do
            line = output.gets
            raise "oceanbase_mcp_server exited before responding" unless line

            begin
              break JSON.parse(line)
            rescue JSON::ParserError
              next
            end
          end
        end

        input.puts JSON.generate(jsonrpc: "2.0", id: 1, method: "initialize", params: {
          protocolVersion: "2025-06-18", capabilities: {}, clientInfo: { name: "Homebrew", version: "1.0" }
        })
        response = read_response.call
        assert_equal "oceanbase_mcp_server", response.dig("result", "serverInfo", "name")

        input.puts JSON.generate(jsonrpc: "2.0", method: "notifications/initialized", params: {})
        input.puts JSON.generate(jsonrpc: "2.0", id: 2, method: "tools/list", params: {})
        response = read_response.call
        assert_includes response.dig("result", "tools").map { |tool| tool["name"] }, "execute_sql"
      end
    ensure
      input.close unless input.closed?
      Process.kill("TERM", process.pid) if process.alive?
      Process.kill("KILL", process.pid) unless process.join(5)
    end
  end
