  def install
    build_resources = %w[
      flit-core
      packaging
      pathspec
      poetry-core
      setuptools
      calver
      cython
      tomlkit
      trove-classifiers
      vcs-versioning
      setuptools-scm
      pluggy
      hatchling
      hatch-fancy-pypi-readme
      hatch-vcs
    ]

    # Cython is only needed at build time; skip compiling Cython itself
    ENV["NO_CYTHON_COMPILE"] = "true"

    venv = virtualenv_create(libexec, "python3.13")
    build_resources.each do |name|
      venv.pip_install resource(name), build_isolation: false
    end
    venv.pip_install resources.reject { |r| build_resources.include?(r.name) }, build_isolation: false
    venv.pip_install_and_link buildpath, build_isolation: false
  end

  test do
    output_log = testpath/"tofuref.log"
    pid = if OS.mac?
      spawn "script", "-q", File::NULL, bin/"tofuref", [:out, :err] => output_log.to_s
    else
      spawn "script", "-q", "-c", bin/"tofuref", File::NULL, [:out, :err] => output_log.to_s
    end
    sleep 2
    assert Process.kill(0, pid)
    Process.kill("TERM", pid)
    Process.wait(pid)
    output = output_log.read
    refute_match "No such device or address", output
    refute_match "Traceback", output
  rescue Errno::ESRCH
    flunk "tofuref exited before it could be terminated"
  end
