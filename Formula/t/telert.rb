  def install
    build_resources = %w[
      flit-core
      packaging
      pathspec
      poetry-core
      setuptools
      calver
      tomlkit
      trove-classifiers
      vcs-versioning
      setuptools-scm
      pluggy
      hatchling
      hatch-vcs
      wheel
    ]

    venv = virtualenv_create(libexec, "python3.13")
    build_resources.each do |name|
      venv.pip_install resource(name), build_isolation: false
    end
    venv.pip_install resources.reject { |r| build_resources.include?(r.name) }, build_isolation: false
    venv.pip_install_and_link buildpath, build_isolation: false
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/telert --version")

    # Delivering notifications needs a remote service; exercise local provider configuration instead.
    assert_match "No providers configured", shell_output("#{bin}/telert status")

    system bin/"telert", "config", "endpoint", "--url", "https://example.invalid/hook?m={message}",
           "--name", "brewhook", "--set-default"
    assert_match "endpoint (default)", shell_output("#{bin}/telert config list-providers")
    assert_match "brewhook", (testpath/".config/telert/config.json").read
