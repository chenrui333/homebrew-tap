  def install
    build_resources = %w[
      setuptools
      flit-core
      packaging
      pathspec
      calver
      trove-classifiers
      vcs-versioning
      setuptools-scm
      pluggy
      poetry-core
      tomlkit
      hatchling
    ]

    ENV.append_path "PYTHONPATH", formula_opt_libexec("cython")/Language::Python.site_packages("python3.15")

    venv = virtualenv_create(libexec, "python3.15")
    build_resources.each do |name|
      venv.pip_install resource(name), build_isolation: false
    end
    venv.pip_install resources.reject { |resource| build_resources.include?(resource.name) }, build_isolation: false
    venv.pip_install_and_link buildpath, build_isolation: false
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/terrascope --version")

    output = shell_output("#{bin}/terrascope --offline --cache-dir #{testpath}/cache --show-paths")
    assert_match "#{testpath}/cache/terrascope.log", output
    assert_match "off (offline)", output

    output = shell_output("#{bin}/terrascope --set app.min_terminal_width=99 --dump-config")
    assert_match "min_terminal_width: 99", output

    output = shell_output("#{bin}/terrascope --set nope=1 2>&1", 2)
    assert_match "unknown setting 'nope'", output
  end
