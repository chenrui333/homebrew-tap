        port: 9792
      procs:
        "echo test":
          shell: "echo 'Hello, Homebrew!'"
          autostart: false
          description: "test process"
    YAML

    output = shell_output("#{bin}/procmux signal-stop-running 2>&1", 1)
    assert_match "Signal server is not enabled in config", output
  end
