  def install
    venv = virtualenv_create(libexec, "python3.14")
    build_resources = %w[
      setuptools flit-core packaging wheel calver cython pathspec poetry-core trove-classifiers
      vcs-versioning setuptools-scm pluggy hatchling hatch-vcs
    ]
    build_resources.each { |name| venv.pip_install resource(name), build_isolation: false }
    venv.pip_install resources.reject { |r| build_resources.include?(r.name) }, build_isolation: false
    venv.pip_install_and_link buildpath, build_isolation: false
    %w[yq xq tomlq].each do |command|
      generate_completions_from_executable(libexec/"bin/register-python-argcomplete", command,
                                           base_name: command, shell_parameter_format: "--shell=")
    end
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/yq --version")
    (testpath/"input.yaml").write("answer: 42\n")
    (testpath/"input.xml").write("<root><answer>42</answer></root>\n")
    (testpath/"input.toml").write("answer = 42\n")
    assert_equal "42", shell_output("#{bin}/yq '.answer' #{testpath}/input.yaml").strip
    assert_equal "42", shell_output("#{bin}/xq -r '.root.answer' #{testpath}/input.xml").strip
    assert_equal "42", shell_output("#{bin}/tomlq '.answer' #{testpath}/input.toml").strip
  end
