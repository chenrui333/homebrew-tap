  def install
    build_resources = %w[
      flit-core packaging calver poetry-core tomlkit vcs-versioning setuptools-scm pluggy pathspec
      trove-classifiers hatchling hatch-vcs hatch-fancy-pypi-readme
    ]
    ENV.append_path "PYTHONPATH", formula_opt_libexec("cython")/Language::Python.site_packages("python3.15")
    venv = virtualenv_create(libexec, "python3.15")
    build_resources.each do |name|
      venv.pip_install resource(name), build_isolation: false
    end
    venv.pip_install resources.reject { |resource| build_resources.include?(resource.name) }, build_isolation: false
    venv.pip_install_and_link buildpath, build_isolation: false
  end

