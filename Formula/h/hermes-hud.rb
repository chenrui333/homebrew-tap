    (testpath/"hermes").mkpath
    (testpath/"hermes/config.yaml").write <<~YAML
      model:
        default: homebrew-model
        provider: homebrew-provider
    YAML
    output = shell_output("#{bin}/hermes-hud --text")
    assert_match "homebrew-model", output
    assert_match "homebrew-provider", output
