  def install
    # Fix --version to use the PyPI distribution name.
    inreplace "src/agentmeter/cli.py", 'package_name="agentmeter"', 'package_name="agent-usage"'

    build_resources = %w[
      setuptools
      flit-core
      packaging
      pathspec
      trove-classifiers
      vcs-versioning
      setuptools-scm
      pluggy
      hatchling
      hatch-vcs
      hatch-fancy-pypi-readme
    ]

    venv = virtualenv_create(libexec, "python3.14")
    build_resources.each do |name|
      venv.pip_install resource(name), build_isolation: false
    end
    venv.pip_install resources.reject { |r| build_resources.include?(r.name) }, build_isolation: false
    venv.pip_install_and_link buildpath, build_isolation: false

    # Expose only the main CLI; dependency scripts remain under libexec.
    bin.install_symlink libexec/"bin/agentmeter"

    generate_completions_from_executable(bin/"agentmeter", shells: [:fish, :zsh], shell_parameter_format: :click)
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/agentmeter --version")

    output = shell_output("#{bin}/agentmeter stats")
    assert_match "AgentMeter Stats", output
    assert_match "No tool calls recorded.", output
  end
