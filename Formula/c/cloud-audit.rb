      setuptools-scm
      pluggy
      hatchling
      hatch-vcs
      hatch-fancy-pypi-readme
      markupsafe
      jinja2
      dunamai
      uv-dynamic-versioning
    ]

    ENV.prepend_path "PATH", formula_opt_bin("rust")
    ENV.append_path "PYTHONPATH", formula_opt_prefix("maturin")/Language::Python.site_packages("python3.14")
    ENV["CARGO_NET_OFFLINE"] = "true"

    venv = virtualenv_create(libexec, "python3.14")
    build_resources.each do |name|
      venv.pip_install resource(name), build_isolation: false
    end

    # python-dateutil requires setuptools-scm<8; keep that backend out of the modern build environment.
    legacy_venv = virtualenv_create(buildpath/"dateutil-build", "python3.14")
    %w[flit-core setuptools packaging wheel setuptools-scm-legacy].each do |name|
      legacy_venv.pip_install resource(name), build_isolation: false
    end
    with_env(PYTHONPATH: legacy_venv.site_packages.to_s) do
      venv.pip_install resource("python-dateutil"), build_isolation: false
    end

    venv.pip_install resources.reject { |r|
      build_resources.include?(r.name) || r.name == "python-dateutil"
    }, build_isolation: false
    venv.pip_install_and_link buildpath, build_isolation: false
  end

