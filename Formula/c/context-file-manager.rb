  def install
    build_resources = %w[
      setuptools
      flit-core
      poetry-core
      packaging
      pathspec
      calver
      trove-classifiers
      vcs-versioning
      setuptools-scm
      pluggy
      hatchling
      hatch-vcs
      hatch-fancy-pypi-readme
      markupsafe
      jinja2
      tomlkit
      dunamai
      uv-dynamic-versioning
      wheel
    ]

    venv = virtualenv_create(libexec, "python3.13")
    build_resources.each do |name|
      venv.pip_install resource(name), build_isolation: false
    end
    venv.pip_install resources.reject { |resource| build_resources.include?(resource.name) }, build_isolation: false
    venv.pip_install_and_link buildpath, build_isolation: false
  end

  test do
    # FIXME: Upstream does not expose a version command; replace this with a version assertion when available.
    repo = testpath/"repository"
    assert_match "No files in repository", shell_output("#{bin}/cfm --repo #{repo} list")

    (testpath/"note.md").write("Homebrew context test\n")
    system bin/"cfm", "--repo", repo, "add", testpath/"note.md", "Test note"
    assert_match "note.md", shell_output("#{bin}/cfm --repo #{repo} list --format json")
    system bin/"cfm", "--repo", repo, "get", "note.md", testpath/"retrieved.md"
    assert_equal "Homebrew context test\n", (testpath/"retrieved.md").read
  end
